// Regenerates js/data/audio-manifest.js from tools/awana-track-map.json plus
// whatever audio files actually exist on disk. Dev-only; run after adding or
// re-ingesting audio:  node tools/build-audio-manifest.mjs
//
// Manifest shape (consumed by the future js/lib/audio.js player — plans.html §4):
//   read:     { common: {ref: entry}, niv84: {ref: entry}, esv: {...}, ... }
//   handbook: { hg: [entry…], wr: [...], ss: [...] }   (in handbook track order)
//   songs:    { common: {name: entry}, niv84: {ref: entry}, ... }
// A read lookup for (ref, translation) checks read[translation][ref] first,
// then read.common[ref] (book-list clips are translation-independent).
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const MAP = JSON.parse(readFileSync(join(ROOT, 'tools/awana-track-map.json'), 'utf8'));

function duration(relPath) {
  const out = execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration',
    '-of', 'csv=p=0', join(ROOT, relPath)], { encoding: 'utf8' }).trim();
  return Math.round(parseFloat(out) * 10) / 10;
}

const manifest = { read: { common: {} }, handbook: {}, songs: { common: {} } };
for (const t of Object.keys(MAP.translations)) { manifest.read[t] = {}; manifest.songs[t] = {}; }
let missing = 0;

for (const [bookId, book] of Object.entries(MAP.books)) {
  manifest.handbook[bookId] = [];
  const nums = Object.keys(book.tracks).map(Number).sort((a, b) => a - b);
  for (const n of nums) {
    const e = book.tracks[n];
    if (e.type === 'verse') {
      for (const t of Object.keys(MAP.translations)) {
        const file = e.out.replace('{t}', t);
        if (!existsSync(join(ROOT, file))) { console.warn(`missing: ${file}`); missing++; continue; }
        const entry = { file, duration: duration(file) };
        for (const ref of e.refs) manifest.read[t][ref] = entry;
      }
    } else if (e.type === 'verse-list') {
      if (!existsSync(join(ROOT, e.out))) { console.warn(`missing: ${e.out}`); missing++; continue; }
      const entry = { file: e.out, duration: duration(e.out) };
      for (const ref of e.refs) manifest.read.common[ref] = entry;
    } else if (e.type === 'lesson' || e.type === 'story') {
      if (!existsSync(join(ROOT, e.out))) { console.warn(`missing: ${e.out}`); missing++; continue; }
      manifest.handbook[bookId].push({ file: e.out, duration: duration(e.out),
        type: e.type, title: e.title, section: e.section || null });
    } else if (e.type === 'song') {
      if (!existsSync(join(ROOT, e.out))) { console.warn(`missing: ${e.out}`); missing++; continue; }
      const name = e.out.split('/').pop().replace('.m4a', '');
      manifest.songs.common[name] = { file: e.out, duration: duration(e.out), title: e.title };
    }
  }
}

// Owner-provided verse songs (plans.html §4.8): audio/songs/<translation>/<ref-slug>.m4a
// are picked up automatically when present, keyed back to refs via slug match.
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const refBySlug = {};
for (const book of Object.values(MAP.books))
  for (const e of Object.values(book.tracks))
    if (e.refs) for (const r of e.refs) refBySlug[slug(r)] = r;
for (const t of Object.keys(MAP.translations)) {
  const dir = join(ROOT, 'audio/songs', t);
  if (!existsSync(dir)) continue;
  for (const f of readdirSync(dir).filter((f) => f.endsWith('.m4a') || f.endsWith('.mp3'))) {
    const ref = refBySlug[f.replace(/\.(m4a|mp3)$/, '')];
    const file = `audio/songs/${t}/${f}`;
    if (ref) manifest.songs[t][ref] = { file, duration: duration(file) };
    else console.warn(`song file has no matching ref slug: ${file}`);
  }
}

const body = `// GENERATED by tools/build-audio-manifest.mjs — do not edit by hand.
// Official Awana Sparks handbook recordings; see README for source & copyright.
// Gaps (no recording, device speech fallback): ${JSON.stringify(MAP.gaps)}
export const AUDIO = ${JSON.stringify(manifest, null, 1)};
`;
writeFileSync(join(ROOT, 'js/data/audio-manifest.js'), body);
const counts = Object.entries(manifest.read).map(([t, m]) => `${t}:${Object.keys(m).length}`).join(' ');
console.log(`read refs — ${counts}`);
console.log(`handbook — ${Object.entries(manifest.handbook).map(([b, a]) => `${b}:${a.length}`).join(' ')}`);
console.log(`songs — common:${Object.keys(manifest.songs.common).length}`);
console.log(missing ? `MISSING FILES: ${missing}` : 'all mapped files present');
